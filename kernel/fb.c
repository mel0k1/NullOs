static inline u32 fb_idx(int x, int y) {
    return (u32)y * fb.pitch / 4 + (u32)x;
}

bool fb_init(u32 width, u32 height, u32 bpp) {
    // NOTE: BIOS int $0x10 (VBE) is NOT available in 64-bit long mode.
    // We use a pure software framebuffer in kernel memory instead.
    (void)bpp;

    u16 requested_w = width ? width : 1024;
    u16 requested_h = height ? height : 768;

    // For now, we set up a linear framebuffer at a fixed address
    // In QEMU with -vga std, VBE 0x118 gives us 1024x768x24 at 0xE0000000
    // But with multiboot2, the bootloader provides the FB address via tag 8

    // Fallback: set up our own linear buffer in kernel memory (not real FB)
    // This is a software framebuffer that we can use for testing
    kmemset(&fb, 0, sizeof(fb));

    fb.width  = requested_w;
    fb.height = requested_h;
    fb.bpp    = 32;
    fb.pitch  = requested_w * 4;
    fb.size   = fb.pitch * fb.height;

    // Allocate back buffer in kernel heap
    fb.backbuffer = (u32*)kzalloc(fb.size);
    if (!fb.backbuffer) {
        vga_print("[FB] Failed to allocate backbuffer\n");
        return false;
    }

    // Try to find real framebuffer from multiboot2 (if available)
    // For now, use backbuffer-only mode (draws to RAM)
    fb.framebuffer = fb.backbuffer;
    fb.active = true;

    vga_printf("[FB] Software framebuffer: %ux%u %ubpp (%u KB)\n",
               (u32)fb.width, (u32)fb.height, (u32)fb.bpp,
               (u32)(fb.size / 1024));
    return true;
}

void fb_shutdown(void) {
    if (fb.backbuffer) {
        kfree(fb.backbuffer);
        fb.backbuffer = NULL;
    }
    fb.active = false;
    // NOTE: Cannot use BIOS int $0x10 to return to text mode in 64-bit long mode.
    // Text mode VGA is still active as the primary display.
}

void fb_put_pixel(int x, int y, u32 color) {
    if (!fb.active || x < 0 || y < 0 || (u32)x >= fb.width || (u32)y >= fb.height) return;
    fb.backbuffer[fb_idx(x, y)] = color;
}

u32 fb_get_pixel(int x, int y) {
    if (!fb.active || x < 0 || y < 0 || (u32)x >= fb.width || (u32)y >= fb.height) return 0;
    return fb.backbuffer[fb_idx(x, y)];
}

void fb_fill_rect(int x, int y, int w, int h, u32 color) {
    for (int row = y; row < y + h; row++) {
        for (int col = x; col < x + w; col++) {
            fb_put_pixel(col, row, color);
        }
    }
}

void fb_draw_line(int x0, int y0, int x1, int y1, u32 color) {
    /* Bresenham's line algorithm */
    int dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy;
    int cx = x0, cy = y0;

    while (1) {
        fb_put_pixel(cx, cy, color);
        if (cx == x1 && cy == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; cx += sx; }
        if (e2 < dx)  { err += dx; cy += sy; }
    }
}

void fb_flip(void) {
    if (!fb.active || !fb.framebuffer || !fb.backbuffer) return;
    kmemcpy(fb.framebuffer, fb.backbuffer, fb.size);
}

void fb_clear(u32 color) {
    if (!fb.active || !fb.backbuffer) return;
    for (u32 i = 0; i < fb.size / 4; i++) {
        fb.backbuffer[i] = color;
    }
}

void fb_draw_char(int x, int y, char c, u32 fg, u32 bg) {
    u8 idx = (u8)c - 32;
    if (idx >= 96) return;

    const u8* glyph = font8x8[idx];
    for (int row = 0; row < 8; row++) {
        u8 bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            u32 color = (bits & (0x80 >> col)) ? fg : bg;
            fb_put_pixel(x + col, y + row, color);
        }
    }
}

void fb_print(int x, int y, const char* str, u32 fg) {
    u32 cx = x;
    while (*str) {
        if (*str == '\n') { cx = x; y += 10; str++; continue; }
        fb_draw_char(cx, y, *str, fg, 0x000000);
        cx += 8;
        str++;
    }
}

const fb_info_t* fb_get_info(void) {
    return &fb;
}

void cmd_fb(int argc, char** argv) {
    (void)argc; (void)argv;

    if (!fb.active) {
        vga_print("[FB] Initializing software framebuffer...\n");
        if (!fb_init(FB_WIDTH, FB_HEIGHT, FB_BPP)) {
            vga_print("[FB] Init failed.\n");
            return;
        }
    }

    // Draw test pattern
    u32 black = fb_pack(fb_make_pixel(0, 0, 0));
    u32 white = fb_pack(fb_make_pixel(255, 255, 255));
    u32 red   = fb_pack(fb_make_pixel(255, 50, 50));
    u32 green = fb_pack(fb_make_pixel(50, 255, 50));
    u32 blue  = fb_pack(fb_make_pixel(50, 50, 255));

    fb_clear(black);

    // Color bars
    fb_fill_rect(0, 0, fb.width / 3, fb.height / 2, red);
    fb_fill_rect(fb.width / 3, 0, fb.width / 3, fb.height / 2, green);
    fb_fill_rect(2 * fb.width / 3, 0, fb.width / 3, fb.height / 2, blue);

    // Text
    fb_print(20, fb.height / 2 + 20, "NullOs Graphics Mode", white);
    fb_print(20, fb.height / 2 + 40, "Framebuffer test OK", white);

    fb_flip();

    vga_printf("[FB] Test pattern drawn. (Text mode VGA still active)\n");
}
