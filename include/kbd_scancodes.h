// ============================================================
// Keyboard PS/2 command interface
// ============================================================

#define KBD_CMD_SET_SCANCODE_SET  0xF0
#define KBD_CMD_GET_SCANCODE_SET  0xF0
#define KBD_CMD_SCANCODE_SET_2    0x02
#define KBD_CMD_SCANCODE_SET_1    0x01

#define KBD_CMD_ENABLE_SCANNING   0xF4
#define KBD_CMD_DISABLE_SCANNING  0xF5
#define KBD_CMD_RESET             0xFF

#define KBD_REPLY_ACK             0xFA
#define KBD_REPLY_RESEND          0xFE
#define KBD_REPLY_SELF_TEST_OK    0xAA
#define KBD_REPLY_BAT_OK          0xAA

// Send command to keyboard controller
void kbd_controller_cmd(u8 cmd);

// Send command to keyboard (via data port)
void kbd_send_cmd(u8 cmd);

// Wait for keyboard acknowledge
bool kbd_wait_ack(u32 timeout_ms);

// Switch keyboard to scancode set 2
// Returns true if successful
bool kbd_switch_to_set2(void);

// Translate a Set 2 scancode to Set 1 equivalent
// Returns Set 1 make scancode, or 0 if unmapped
u8 kbd_set2_to_set1(u8 scancode, bool extended);

