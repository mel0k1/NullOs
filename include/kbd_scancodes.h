/*
 * Scancode Set 2 → ASCII translation tables
 * Set 2 is the default for most PS/2 keyboards.
 * 
 * Set 2 scancodes are different from Set 1:
 *   - Make codes: single byte (most keys) or multi-byte (E0 prefix for extended)
 *   - Break codes: F0 <make_code> (two bytes)
 *   - Extended keys: E0 <make_code> (two bytes)
 *   - Extended break: E0 F0 <make_code> (three bytes)
 *
 * This module provides translation from Set 2 to the internal key code
 * used by the keyboard driver.
 */

// Set 2 make code → Set 1 make code translation (0 = no mapping)
static const u8 scancode_set2_to_set1[] = {
    /* 00 */ 0x00,
    /* 01 */ 0x29,  // Esc → 0x01 (set1: Esc)
    /* 02 */ 0x02,  // 1
    /* 03 */ 0x03,  // 2
    /* 04 */ 0x04,  // 3
    /* 05 */ 0x05,  // 4
    /* 06 */ 0x06,  // 5
    /* 07 */ 0x07,  // 6
    /* 08 */ 0x08,  // 7
    /* 09 */ 0x09,  // 8
    /* 0A */ 0x0A,  // 9
    /* 0B */ 0x0B,  // 0
    /* 0C */ 0x1E,  // -
    /* 0D */ 0x30,  // =
    /* 0E */ 0x2B,  // \ (backslash, ANSI)
    /* 0F */ 0x10,  // Backspace → 0x0E... actually let's map directly to set1 scancodes
    // Actually, let me map to SET 1 make codes directly so the existing
    // translation tables (scancode_to_char / scancode_to_char_shift) can be reused.
    // Set 1: Esc=0x01, 1=0x02, 2=0x03, ... 0=0x0B, -=0x0C, ==0x0D, BS=0x0E,
    //        Tab=0x0F, q=0x10, w=0x11, ..., ]=0x1B, ^=0x1D, \=0x2B
};

